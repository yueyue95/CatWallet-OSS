const localeMessages: Record<Locale, Record<string, string>> = {
  en: messages.en,
  "pt-BR": messages["pt-BR"],
  "zh-CN": zhCNMessages,
};

const LocaleContext = React.createContext<{
  currency: Currency;
  currencySymbol: string;
  formatCurrency: (value: number) => string;
  formatDate: (
    date: string | Date,
    options?: Intl.DateTimeFormatOptions,
  ) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  locale: Locale;
  setCurrency: (currency: Currency) => void;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
} | null>(null);

function resolveLocale(value?: string | null): Locale {
  const normalized = value?.toLowerCase() ?? "";

  if (normalized.startsWith("pt")) return "pt-BR";
  if (normalized.startsWith("zh")) return "zh-CN";

  return "en";
}

function resolveCurrency(candidate: string | null | undefined): Currency {
  if (isSupportedCurrency(candidate)) return candidate;
  return DEFAULT_CURRENCY;
}

function readStoredLocalePreferences(): { currency: Currency; locale: Locale } {
  const storedLocale = window.localStorage.getItem(localeStorageKey);
  const locale = storedLocale ? resolveLocale(storedLocale) : "zh-CN";
  return { currency: resolveCurrency(getStoredCurrency()), locale };
}

function translateMessage(locale: Locale, key: string): string {
  const candidates = [
    key,
    `data.category.${key}`,
    `data.group.${key}`,
    `common.${key}`,
  ];

  for (const candidate of candidates) {
    const localized = localeMessages[locale][candidate];
    if (localized) return localized;

    const fallback = messages.en[candidate as keyof Messages];
    if (fallback) return fallback;
  }

  return key;
}

function formatLocalizedDate(
  locale: Locale,
  date: string | Date,
  options?: Intl.DateTimeFormatOptions,
): string {
  const value =
    typeof date === "string" && /^\d{4}-\d{2}-\d{2}$/.test(date)
      ? new Date(`${date}T00:00:00`)
      : new Date(date);

  return new Intl.DateTimeFormat(locale, options).format(value);
}

export function LanguageProvider({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  const [locale, setLocaleState] = React.useState<Locale>("zh-CN");
  const [currency, setCurrencyState] =
    React.useState<Currency>(DEFAULT_CURRENCY);
  const [preferencesLoaded, setPreferencesLoaded] = React.useState(false);

  React.useEffect(() => {
    const { currency: nextCurrency, locale: nextLocale } =
      readStoredLocalePreferences();

    setLocaleState(nextLocale);
    setCurrencyState(nextCurrency);
    setPreferencesLoaded(true);
  }, []);

  React.useEffect(() => {
    if (!preferencesLoaded) return;
    document.documentElement.lang = locale;
    window.localStorage.setItem(localeStorageKey, locale);
  }, [locale, preferencesLoaded]);

  React.useEffect(() => {
    if (!preferencesLoaded) return;
    setStoredCurrency(currency);
  }, [currency, preferencesLoaded]);

  const value = React.useMemo(
    () => ({
      currency,
      currencySymbol: getCurrencySymbol(currency, locale),
      formatCurrency(value: number) {
        return formatCurrency(value, locale, currency);
      },
      formatDate(date: string | Date, options?: Intl.DateTimeFormatOptions) {
        return formatLocalizedDate(locale, date, options);
      },
      formatNumber(value: number, options?: Intl.NumberFormatOptions) {
        return new Intl.NumberFormat(locale, options).format(value);
      },
      locale,
      setCurrency(nextCurrency: Currency) {
        setCurrencyState(resolveCurrency(nextCurrency));
      },
      setLocale(nextLocale: Locale) {
        setLocaleState(nextLocale);
      },
      t(key: string) {
        return translateMessage(locale, key);
      },
    }),
    [currency, locale],
  );

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useI18n() {
  const context = React.useContext(LocaleContext);

  if (!context) {
    throw new Error("useI18n must be used within LanguageProvider.");
  }

  return context;
}
